"""Staging and spawning a session.

The staging work is entirely freeskate's -- this module writes a scratch map
profile, asks `freeskate play _loader --dry-run` to stage it and print the argv
it would have used, then launches that argv itself with a few loader-owned flags
appended. That keeps freeskate's build_command() the single source of truth for
the demo-path flags, and matches what play_monitored.sh / play_fixed.sh already do.
"""

from __future__ import annotations

import os
import re
import shutil
import signal
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path

from . import art, config
from .catalog import MapEntry, Pack

ANSI = re.compile(r"\x1b\[[0-9;]*m")


class LaunchError(Exception):
    pass


# --------------------------------------------------------------------------
# The scratch map profile
# --------------------------------------------------------------------------


def _toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "") + "'"


def write_profile(pack: Pack, entry: MapEntry) -> Path:
    """Generate freeskate/maps/_loader/map.toml for one map of one pack."""
    lines = [
        "# Generated by skate3loader on every launch - safe to delete.",
        f"# Target: {pack.name} / {entry.name} ({entry.world_id})",
        "",
        "[map]",
        f"name = {_toml_value(pack.name + ' - ' + entry.name)}",
        f"description = {_toml_value('Staged by skate3loader.')}",
        # The macro is passed on the command line instead, so the profile does
        # not pin one.
        "macro = 'none'",
        "",
        # Stock DLC stays off for CUSTOM packs: a custom package alongside the
        # shipped Danny Way / Maloof content overloads the boot content scan and
        # crashes it. A "stock" pack is the opposite case - the official content
        # IS the map, so it goes on and nothing custom is staged beside it.
        "[dlc]",
        f"enabled = {'true' if pack.kind == 'stock' else 'false'}",
    ]

    if pack.kind == "stock":
        # Already installed under the real user root; freeskate mirrors that
        # subtree into the staged tree. Nothing to drop in or hand-place.
        lines += [""]
    elif pack.kind == "stfs":
        # A signed container installs itself: dropped into the dlc/ folder, the
        # engine's own DLC scan registers it and writes a correct header. That
        # avoids the whole hand-made-header problem raw .big packs have.
        lines += [
            "auto_install = true",
            f"dropin = [{_toml_value(pack.big)}]",
            "",
        ]
    else:
        lines += [
            "",
            "[[dlc_packages]]",
            f"source = {_toml_value(pack.big)}",
            f"package = {_toml_value(pack.package)}",
            f"name = {_toml_value(pack.name)}",
            f"header = {_toml_value(pack.header)}",
            "",
        ]

    lines += [
        "# After detecting new content the game relaunches itself asking for the",
        "# retail executable name; alias it so the relaunch resolves.",
        "[[game_files]]",
        f"source = {_toml_value(str(config.INSTALL / 'game' / 'default.xex'))}",
        "target = 'sk83_na_f.xex'",
        "",
        "[launch]",
        "# Signed in so the Locations menu is navigable.",
        "signed_in = true",
    ]
    if pack.settings:
        lines += ["", "[settings]"]
        lines += [f"{key} = {_toml_value(value)}" for key, value in sorted(pack.settings.items())]

    config.LOADER_PROFILE_DIR.mkdir(parents=True, exist_ok=True)
    manifest = config.LOADER_PROFILE_DIR / "map.toml"
    manifest.write_text("\n".join(lines) + "\n")
    return manifest


# --------------------------------------------------------------------------
# Pre-launch hygiene
# --------------------------------------------------------------------------


def game_running() -> bool:
    """Whether a LIVE game process exists.

    Zombies do not count. A defunct child still matches `pgrep -x skate3`, and
    treating it as running is fatal here: `kill_running_game` then SIGKILLs a
    corpse for its whole timeout and raises, which is what wedged the launcher
    on an in-game map switch - the game had exited, its process just had not
    been reaped yet.
    """
    found = subprocess.run(["pgrep", "-x", "skate3"], capture_output=True, text=True)
    if found.returncode != 0:
        return False
    for line in found.stdout.split():
        try:
            with open(f"/proc/{line}/stat", "r") as handle:
                state = handle.read().split(") ", 1)[1].split()[0]
        except (OSError, IndexError):
            continue
        if state != "Z":
            return True
    return False


def kill_running_game(timeout: float = 10.0) -> None:
    """Stop any running game and release its shared memory.

    Two hard-won reasons this is not optional: freeskate's own single-instance
    guard refuses to stage while a game is running, and a killed game leaks a
    4.5 GiB /dev/shm segment that fills the tmpfs and makes the NEXT startup hang
    forever.
    """
    deadline = time.monotonic() + timeout
    while game_running() and time.monotonic() < deadline:
        # SIGKILL every time round: a game mid-teardown can ignore gentler
        # signals, and freeskate refuses to stage while ANY copy is alive, so a
        # half-dead process turns the next relaunch into a hard failure.
        subprocess.run(["pkill", "-9", "-x", "skate3"], capture_output=True)
        time.sleep(0.25)
    if game_running():
        raise LaunchError(
            "a previous Skate 3 process would not exit; kill it manually "
            "(pkill -9 -x skate3) and try again"
        )
    for leaked in Path("/dev/shm").glob("xenia_memory_*"):
        try:
            leaked.unlink()
        except OSError:
            pass


