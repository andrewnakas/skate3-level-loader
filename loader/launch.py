@dataclass
class Session:
    process: subprocess.Popen
    argv: list[str]
    log_file: Path
    target_world: str

    def wait(self) -> int:
        return self.process.wait()

    def stop(self) -> None:
        if self.process.poll() is None:
            try:
                self.process.terminate()
                self.process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                # kill() only signals; without the wait() the child stays a
                # ZOMBIE, which `pgrep` still reports and `kill_running_game`
                # then refuses to proceed past.
                self.process.kill()
                try:
                    self.process.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    pass
            except ProcessLookupError:
                pass


def _apply_overrides(argv: list[str], overrides: dict[str, str | None]) -> list[str]:
    """Append flags, replacing any freeskate already set rather than duplicating.

    A value of None REMOVES the flag instead of setting it. That is not the same
    as setting it to the empty string: `--skate3_warp_world=` makes the cvar
    parser take the NEXT argv entry as the value, so disabling the warp that way
    produced `requested world '--skate3_warp_substitute_item=false'` and left it
    very much enabled.
    """
    out = []
    for part in argv:
        name = part.split("=", 1)[0]
        if part.startswith("--") and name in {f"--{k}" for k in overrides}:
            continue
        out.append(part)
    out.extend(f"--{key}={value}" for key, value in overrides.items()
               if value is not None)
    return out


def launch(
    pack: Pack,
    entry: MapEntry,
    macro: str,
    all_packs: list[Pack] | None = None,
    binary: Path | None = None,
    windowed: bool = False,
    settle_ms: int = DEFAULT_SETTLE_MS,
    delay_ms: int = 260,
    open_picker: bool = False,
    extra_cvars: dict[str, str] | None = None,
) -> Session:
    """Stage the pack, then spawn the game aimed at one map."""
    binary = Path(binary) if binary else config.default_binary()
    if not binary.is_file():
        raise LaunchError(f"game binary not found at {binary}")

    kill_running_game()
    write_profile(pack, entry)

    # Start from a clean log so the watcher never reads a previous session's
    # milestones. freeskate rotates it during staging, so this must come after.
    argv = stage(macro, settle_ms=settle_ms, delay_ms=delay_ms)
    argv[0] = str(binary)

    overrides = {
        # Without this the tail sees nothing until the buffer flushes.
        "log_flush_interval": "1",
        # The in-game loading cover. Drawing it inside the game's own window is
        # what makes menu automation invisible: an external window cannot be
        # kept above a fullscreen game reliably (impossible on Wayland, and on
        # X11 the fullscreen layer outranks always-on-top).
        "skate3_loader_overlay": "true",
        "skate3_loader_overlay_title": entry.name,
        "skate3_loader_overlay_subtitle": pack.name,
        "skate3_loader_overlay_hue": f"{art.hue_for(entry.world_id):.4f}",
        **_level_picker_cvars(pack, all_packs),
        "skate3_loader_open_picker": "true" if open_picker else "false",
        # -1 leaves the boot path alone; otherwise the engine walks the menu to
        # this map using cursor feedback, which is far quicker than a fixed
        # 40-press macro and stops exactly at the end of the list.
        # Engine-side boot navigation stays off: the pad macro above is the
        # path that is actually verified to land on the right map.
        "skate3_loader_boot_index": "-1",
        # Repoint every map row at the world we actually want. The identity a
        # Locations row carries is a pair of HASHES in the item (+0x18/+0x1C)
        # plus a per-world object at +0x00; copying them from the wanted map's
        # item onto every row makes ANY row load it. Measured at ~60 ms, once.
        #
        # This does NOT replace the navigation above, it backstops it: with both
        # active, a macro that lands on the wrong row still loads the right map,
        # and a pack whose sub-list order we guessed wrong stops mattering.
        "skate3_warp_world": entry.world_id,
        "skate3_warp_substitute_item": "true",
        # Skip loading the stock world entirely. These two redirect the BOOT
        # stream to the requested map, so University is never loaded - the boot
        # streams the map we actually want. On their own they leave the session
        # pointing at the stock world and the renderer with nothing to draw
        # (a black screen); the menu confirm above then fixes the session, with
        # the map's data already resident.
        #
        # Measured: 27.1 / 27.3 / 27.2 s to playable against 30.7 / 32.5 s with
        # the stock world loaded first, and MORE consistent, because the
        # variable-cost University load is gone. The black stretch is invisible
        # behind the in-engine loading overlay.
        "skate3_warp_substitute_folder": "true",
        "skate3_warp_substitute_slug": "true",
        # The frontend's 4-second boot hold. Between language select and the EA
        # logo it runs a timer that accumulates the frame delta and only lets
        # boot continue at 4000 ms; the guest main thread is asleep for all of
        # it (measured: zero new guest calls for 4.18 s, Main XThread under 5%
        # of a core). Completing it on the first tick is 4.1 s off every boot,
        # and it is engine-gated to the pre-press-start window.
        "skate3_boot_skip_fe_hold": "true",
        # Deferred overlapped completions sleep before running and again before
        # the XN_SYS_UI notification, serialised on one kernel dispatch thread.
        # A boot performs exactly one, so this is only ~0.25 s - but it is free.
        "kernel_overlapped_delay_ms": "0",
        # Emits `fe-debug: stack ...` on every screen change - the menu-state
        # feedback channel the loader uses to tell navigation from streaming.
        # The middle Xbox button opens the level picker. SDL drops the Guide
        # button unless this is on, so the picker_chord default ("guide")
        # would silently never fire without it.
        "guide_button": "true",
        "skate3_fe_debug": "true",
        "skate3_hang_watchdog_seconds": "15",
        # A pack whose maps are SPOTS inside one world cannot use the row
        # patch. PatchItemEntries finds its template by the wanted world's pack
        # record, so when 18 entries all report world_id "San Vanelona" it
        # repoints every row at whichever spot matched first and all 18 load
        # the same place. Those packs navigate by row instead - see
        # Pack.spots_share_world and navigate.build_macro's `row_patch`.
        **({"skate3_warp_substitute_item": "false"} if pack.spots_share_world else {}),
        # Leave the warp completely alone for a pack whose world ids match no
        # spawn node - see Pack.warp_safe. Handing it a world it cannot resolve
        # makes it substitute a spawn node that does not exist, the world's
        # geometry never arrives, and on screen you get the skybox and fall
        # through it. Empty disables the whole warp, so the game reaches the map
        # by ordinary menu navigation instead - slower, because the stock world
        # loads first, but correct.
        #
        # This must come AFTER the enabling defaults above; a dict literal takes
        # the last value for a key.
        **({} if pack.warp_safe else {
            # None removes the flag; empty would be read as "value is the next
            # argv entry" and re-enable the warp with a garbage world name.
            "skate3_warp_world": None,
            "skate3_warp_substitute_folder": "false",
            "skate3_warp_substitute_slug": "false",
            "skate3_warp_substitute_item": "false",
            "skate3_warp_substitute_node": "false",
            "skate3_warp_substitute_lookup": "false",
        }),
        # Per-pack overrides beat the defaults above. The map.toml [settings]
        # block cannot do it on its own - everything here is appended to the
        # argv afterwards and would win. Danny Way is the case that needs it:
        # its stream folder is DLC_DW_MegaCompund, so the warp's DIST_ + world
        # redirects the boot stream at a directory that does not exist and the
        # world data never arrives (measured 0/3 with the warp on, 3/3 with it
        # off, while every other DLC world is 3/3 WITH it).
        **{str(k): str(v) for k, v in (pack.settings or {}).items()},
        # Investigation flags (--skate3_trace and friends) go last so a caller
        # can override anything above.
        **(extra_cvars or {}),
    }
    argv = _apply_overrides(argv, overrides)
    if windowed and "--fullscreen=false" not in argv:
        argv.append("--fullscreen=false")

    log_file = _log_path(argv)
    if log_file.exists():
        log_file.unlink()

    env = dict(os.environ)
    # X11 rather than Wayland, so the loading screen's keep-above actually binds.
    env["GDK_BACKEND"] = "x11"

    process = subprocess.Popen(argv, cwd=config.RUNTIME, env=env)
    _install_signal_forwarding(process)
    return Session(
        process=process, argv=argv, log_file=log_file, target_world=entry.world_id
    )


def _level_picker_cvars(pack: Pack, all_packs: list[Pack] | None) -> dict[str, str]:
    """Everything the in-game picker needs to list maps across every pack.

    Maps in the staged pack switch in place; maps in any other pack are marked
    and, when chosen, written to the request file for the launcher to act on --
    the installed DLC set is fixed at boot, so those need a relaunch.
    """
    packs = all_packs if all_packs is not None else [pack]
    names: list[str] = []
    owners: list[str] = []
    indices: list[str] = []
    worlds: list[str] = []
    for candidate in packs:
        for entry in sorted(candidate.maps, key=lambda m: m.sub_index):
            names.append(entry.name)
            owners.append(candidate.id)
            indices.append(str(entry.sub_index))
            # The world id is what the engine repoints the menu rows at, so an
            # in-session switch can target a map without relying on its row.
            worlds.append(entry.world_id)
    if config.REQUEST_FILE.exists():
        config.REQUEST_FILE.unlink()
    return {
        "skate3_loader_levels": "|".join(names),
        "skate3_loader_level_packs": "|".join(owners),
        "skate3_loader_level_indices": "|".join(indices),
        "skate3_loader_level_worlds": "|".join(worlds),
        "skate3_loader_current_pack": pack.id,
        "skate3_loader_request_path": str(config.REQUEST_FILE),
    }


def read_request() -> tuple[str, int] | None:
    """A pending relaunch request from the in-game picker: (pack id, map index)."""
    try:
        lines = config.REQUEST_FILE.read_text().splitlines()
    except OSError:
        return None
    if len(lines) < 2:
        return None
    try:
        return lines[0].strip(), int(lines[1].strip())
    except ValueError:
        return None


def clear_request() -> None:
    try:
        config.REQUEST_FILE.unlink()
    except OSError:
        pass


def _log_path(argv: list[str]) -> Path:
    for part in argv:
        if part.startswith("--log_file="):
            return Path(part.split("=", 1)[1])
    return config.LOG_FILE


def _install_signal_forwarding(process: subprocess.Popen) -> None:
    """Never leave the game orphaned holding its shm segment."""

    def forward(_signum, _frame):
        try:
            process.terminate()
        except ProcessLookupError:
            pass

    for sig in (signal.SIGINT, signal.SIGTERM):
        try:
            signal.signal(sig, forward)
        except ValueError:
            # Not on the main thread; the GUI installs its own handling.
            pass


def clear_profile() -> None:
    """Remove the scratch profile (used on exit; purely cosmetic)."""
    if config.LOADER_PROFILE_DIR.is_dir():
        shutil.rmtree(config.LOADER_PROFILE_DIR, ignore_errors=True)
